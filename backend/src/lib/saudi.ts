/**
 * Transforms formal Arabic text into everyday colloquial Saudi Arabic
 */
export function toSaudiDialect(text: string): string {
  if (!text) return "";
  let saudi = text;

  for (const [pattern, replacement] of SAUDI_REPLACEMENTS) {
    saudi = saudi.replace(pattern, replacement);
  }

  // Clean double spaces or punctuation artifacts
  return saudi.replace(/\s+/g, " ").trim();
}
